#!/usr/bin/env python3
"""Generate the measurement core's hard-wired ROM, its constants, the stimulus of every scenario and the expected
outputs (bit-exact reference model of rtl/snn_core_meas.v).

Core: layer 2, core 0 of the N-MNIST 5 ms spike-count network (tn4096t5so): 256 axons x 256 neurons, int8 weights,
threshold and leak shift of layer 2. Axons are the presynaptic units with a non-zero weight block into the core, in
increasing order (as snn/system.py's Mapping builds them).

Stimulus commands (one per line, hex {cmd[1:0], axon[7:0]}): 0 = spike on axon, 1 = leak tick, 2 = threshold scan,
3 = window marker (the measurement window starts after the first marker and ends at the second).
Real input: the spikes layer 1 sends to this core in event-driven execution of N-MNIST test samples (system model,
input-paced, tick wire), with the leak tick of every step, played in order; the window holds only spikes (or only
the scans), so that each window measures one kind of operation."""
import json, sys, numpy as np
from pathlib import Path
HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
MODEL = REPO / "results/models/nmnist32_pipelined1_dt5000_T66_h4096-4096-4096-4096-4096_w8_th256_s0tn4096t5so/model_int.npz"
N = 256; VB = 16; VMAX, VMIN = 2 ** (VB - 1) - 1, -2 ** (VB - 1)

z = np.load(MODEL); meta = json.loads(str(z["meta"])); W1 = z["W1"].astype(np.int64)
blk = (W1.reshape(4096, 16, 256) != 0).any(2)
pre = np.flatnonzero(blk[:, 0]); assert len(pre) == 256
ROM = W1[pre][:, 0:256]                                    # ROM[axon][neuron]
THETA, K = int(meta["theta"][1]), int(meta["k_leak"][1])

def write_rom():
    lines = ["// Hard-wired weight ROM of layer 2, core 0 (generated by gen_core.py from " + MODEL.parent.name + ").",
             "// One module per neuron (8 output bits), kept in synthesis for routability."]
    for j in range(N):
        lines.append("(* keep_hierarchy *)")
        lines.append(f"module rom_n{j:03d} (input [7:0] a, output reg [7:0] w);")
        lines.append("  always @* case (a)")
        for a in range(256):
            lines.append(f"    8'd{a}: w = 8'h{int(ROM[a, j]) & 0xff:02x};")
        lines.append("    default: w = 8'h00;")
        lines.append("  endcase")
        lines.append("endmodule")
    lines.append("module core_rom (input [7:0] a, output [2047:0] row);")
    for j in range(N):
        lines.append(f"  rom_n{j:03d} u_n{j:03d} (.a(a), .w(row[{8 * j + 7}:{8 * j}]));")
    lines.append("endmodule")
    (HERE / "rtl/core_rom.v").write_text("\n".join(lines) + "\n")
    (HERE / "rtl/core_params.vh").write_text(f"localparam signed [16:0] THETA = 17'sd{THETA};\nlocalparam [3:0] KLEAK = 4'd{K};\n")

def real_spikes(n_samples):
    """Layer-1 spikes routed to layer 2 core 0, with the step boundaries (leak ticks), event-driven input-paced."""
    sys.path.insert(0, sys.argv[1])                          # a snapshot of the committed system model (read-only)
    from snn.system import Mapping, run_sample
    from snn.model import load_int
    from snn.data import EventData
    d = load_int(MODEL); mp = Mapping(d); data = EventData("nmnist32", "test")
    rc, ra = mp.route_core[1], mp.route_axon[1]
    seqs = []
    for i in range(n_samples):
        t, ch, _ = data.get(i)
        r = run_sample(mp, t, ch, "event", 67.0, 5000, 330000, [1] * 5, sync="wire", paced=256, ref_us=0, trace=True)
        tr = r["trace"]; l1 = tr[tr[:, 0] == 0]
        unit = l1[:, 1] * 256 + l1[:, 2]
        hit = rc[unit, 0] == 0
        ev = l1[hit]; ax = ra[unit[hit], 0]
        o = np.argsort(ev[:, 3], kind="stable"); ev, ax = ev[o], ax[o]
        # step boundaries of the input stream (the wire tick), in the same cycle units
        ts = np.sort(t); tt = np.arange(1, 67) * 5000
        wire = np.searchsorted(ts, tt, side="left") * 256
        cmds = []; q = 0
        for c, a in zip(ev[:, 3], ax):
            while q < len(wire) and wire[q] <= c: cmds.append((1, 0)); q += 1
            cmds.append((0, int(a)))
        seqs.append(cmds)
    return seqs

def reference(cmds, use_ref, mode_event=1):
    """Bit-exact model of the core: returns the spikes per operation and the final state."""
    v = np.zeros(N, np.int64); fired = np.zeros(N, np.int64); out = []
    for cmd, a in cmds:
        if cmd == 3: out.append(("M",)); continue
        if cmd == 0:
            for j in range(N):
                s = v[j] + ROM[a, j]; r = min(max(s, VMIN), VMAX)
                if mode_event and r >= THETA and not (use_ref and fired[j]):
                    out.append((j,)); r = 0; fired[j] = 1 if use_ref else fired[j]
                v[j] = r
        elif cmd == 1:
            for j in range(N): v[j] = v[j] - (v[j] >> K); fired[j] = 0
        elif cmd == 2:
            for j in range(N):
                if v[j] >= THETA: out.append((j,)); v[j] = 0
    return out, v, fired

def write_stim(name, cmds, use_ref=0, mode_event=1):
    (HERE / f"stim/{name}.hex").write_text("".join(f"{(c << 8) | a:03x}\n" for c, a in cmds))
    out, v, fired = reference(cmds, use_ref, mode_event)
    seq = []; win = False; n_in_win = 0
    for o in out:
        if o == ("M",): win = not win; continue
        seq.append(o[0]); n_in_win += win
    (HERE / f"stim/{name}.expect").write_text("".join(f"{j}\n" for j in seq))
    n_ops = {k: sum(1 for c, _ in cmds if c == k) for k in (0, 1, 2)}
    return dict(commands=len(cmds), spikes_out=len(seq), spikes_out_in_window=n_in_win, ops=n_ops,
                final_v_min=int(v.min()), final_v_max=int(v.max()), final_v_mean=float(v.mean()))

if __name__ == "__main__":
    write_rom()
    seqs = real_spikes(int(sys.argv[2]) if len(sys.argv) > 2 else 12)
    flat = [c for s in seqs for c in s]
    spk = [c for c in flat if c[0] == 0]
    print(f"real input: {len(spk)} spikes and {sum(1 for c in flat if c[0] == 1)} leak ticks over {len(seqs)} samples")
    warm = flat[: next(i for i in range(len(flat)) if sum(1 for c in flat[:i] if c[0] == 0) >= 300)]   # 300 spikes of warm-up (about two samples), with their ticks
    rest = [c for c in flat[len(warm):] if c[0] == 0]
    assert len(rest) >= 1000, len(rest)
    M = [(3, 0)]
    info = {}
    info["spike"] = write_stim("spike", warm + M + rest[:1000] + M)                         # event-driven adds with compare, no refractory
    info["spike_ref"] = write_stim("spike_ref", warm + M + rest[:1000] + M, use_ref=1)      # with the refractory bits
    info["add"] = write_stim("add", warm + M + rest[:1000] + M, mode_event=0)                # stepped adds, no compare
    info["leak"] = write_stim("leak", warm + M + [(1, 0)] * 200 + M)
    info["thr"] = write_stim("thr", warm + M + [(2, 0)] * 200 + M, mode_event=1)
    rng = np.random.default_rng(1)
    info["spike_rand"] = write_stim("spike_rand", warm + M + [(0, int(a)) for a in rng.integers(0, 256, 1000)] + M)
    info["idle"] = write_stim("idle", warm + M + M)                                          # the testbench idles between the markers
    meta_out = dict(model=MODEL.parent.name, layer=2, core=0, theta=THETA, k_leak=K, axons=pre.tolist()[:4] + ["..."],
                    rom_min=int(ROM.min()), rom_max=int(ROM.max()), rom_zero_frac=float((ROM == 0).mean()), scenarios=info)
    (HERE / "stim/meta.json").write_text(json.dumps(meta_out, indent=1))
    for k, v in info.items(): print(k, v)
