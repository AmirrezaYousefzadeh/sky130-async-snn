#!/usr/bin/env python3
"""Output unit of the N-MNIST 5 ms spike-count network (tn4096t5so) for the sky130 measurement: its hard-wired
4096 x 10 int8 ROM (one kept module per class), constants, stimulus (the real last-layer spikes of event-driven N-MNIST
test samples, with the step ticks) and the expected class spikes (bit-exact reference of rtl/snn_out_meas.v).
Commands (hex {cmd[1:0], src[11:0]}): 0 spike from last-layer neuron src, 1 leak tick, 3 window marker."""
import json, sys, numpy as np
from pathlib import Path
HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
MODEL = REPO / "results/models/nmnist32_pipelined1_dt5000_T66_h4096-4096-4096-4096-4096_w8_th256_s0tn4096t5so/model_int.npz"
z = np.load(MODEL); meta = json.loads(str(z["meta"])); WO = z["W5"].astype(np.int64)        # 4096 x 10
TH, KO, C = int(meta["theta_out"]), int(meta["k_out"]), WO.shape[1]
OMAX, OMIN = 2 ** 15 - 1, -2 ** 15

def write_rom():
    L = [f"// Hard-wired 4096 x {C} output ROM of {MODEL.parent.name} (generated by gen_out.py), one kept module per class."]
    for c in range(C):
        L += ["(* keep_hierarchy *)", f"module orom_c{c} (input [11:0] a, output reg [7:0] w);", "  always @* case (a)"]
        L += [f"    12'd{i}: w = 8'h{int(WO[i, c]) & 0xff:02x};" for i in range(4096)]
        L += ["    default: w = 8'h00;", "  endcase", "endmodule"]
    L.append(f"module out_rom (input [11:0] a, output [{8 * C - 1}:0] row);")
    L += [f"  orom_c{c} u_c{c} (.a(a), .w(row[{8 * c + 7}:{8 * c}]));" for c in range(C)]
    L.append("endmodule")
    (HERE / "rtl/out_rom.v").write_text("\n".join(L) + "\n")
    (HERE / "rtl/out_params.vh").write_text(f"localparam signed [16:0] THETA_OUT = 17'sd{TH};\nlocalparam [3:0] KOUT = 4'd{KO};\nlocalparam integer NC = {C};\n")

def real_stream(snap, n_samples):
    sys.path.insert(0, snap)
    from snn.system import Mapping, run_sample
    from snn.model import load_int
    from snn.data import EventData
    d = load_int(MODEL); mp = Mapping(d); data = EventData("nmnist32", "test"); cmds = []
    for i in range(n_samples):
        t, ch, _ = data.get(i)
        r = run_sample(mp, t, ch, "event", 67.0, 5000, 330000, [1] * 5, sync="wire", paced=256, ref_us=0, trace=True)
        tr = r["trace"]; l5 = tr[tr[:, 0] == 4]; o = np.argsort(l5[:, 3], kind="stable"); l5 = l5[o]
        ts = np.sort(t); wire = np.searchsorted(ts, np.arange(1, 67) * 5000, side="left") * 256; q = 0
        for row in l5:
            while q < len(wire) and wire[q] <= row[3]: cmds.append((1, 0)); q += 1
            cmds.append((0, int(row[1] * 256 + row[2])))
    return cmds

def reference(cmds):
    o = np.zeros(C, np.int64); cnt = np.zeros(C, np.int64); out = []
    for cmd, a in cmds:
        if cmd == 0:
            for c in range(C):
                x = min(max(o[c] + WO[a, c], OMIN), OMAX)
                if x >= TH: x = 0; cnt[c] += 1; out.append(c)
                o[c] = x
        elif cmd == 1:
            for c in range(C): o[c] = o[c] - (o[c] >> KO)
    return out

def write_stim(name, cmds):
    (HERE / f"stim/{name}.hex").write_text("".join(f"{(c << 12) | a:04x}\n" for c, a in cmds))
    out = reference([x for x in cmds if x[0] != 3])
    (HERE / f"stim/{name}.expect").write_text("".join(f"{c}\n" for c in out))
    return dict(commands=len(cmds), class_spikes=len(out))

if __name__ == "__main__":
    write_rom()
    flat = real_stream(sys.argv[1], int(sys.argv[2]))
    spk = [c for c in flat if c[0] == 0]
    print(f"real last-layer stream: {len(spk)} spikes, {sum(1 for c in flat if c[0] == 1)} ticks")
    warm = flat[: next(i for i in range(len(flat)) if sum(1 for c in flat[:i] if c[0] == 0) >= 200)]
    rest = [c for c in flat[len(warm):] if c[0] == 0]; assert len(rest) >= 1000, len(rest)
    M = [(3, 0)]
    for name, cm in (("ospike", warm + M + rest[:1000] + M), ("oleak", warm + M + [(1, 0)] * 200 + M), ("oidle", warm + M + M)):
        print(name, write_stim(name, cm))
